from itertools import pairwise
from uuid import UUID

import structlog

from sdtoolplus.autogenerated_graphql_client import EmployeeFilter
from sdtoolplus.autogenerated_graphql_client import EngagementFilter
from sdtoolplus.autogenerated_graphql_client import ManagerFilter
from sdtoolplus.depends import GraphQLClient
from sdtoolplus.exceptions import NoValueError
from sdtoolplus.mo.timelines.common import mo_end_to_timeline_end
from sdtoolplus.models import ManagerTimeline
from sdtoolplus.models import ManagerUnit
from sdtoolplus.models import Timeline
from sdtoolplus.models import combine_intervals

logger = structlog.stdlib.get_logger()


async def get_manager_timeline(
    gql_client: GraphQLClient,
    person: UUID,
    engagement: UUID,
) -> ManagerTimeline:
    logger.info(
        "Get MO manager timeline", person=str(person), engagement=str(engagement)
    )

    gql_timeline = await gql_client.get_manager_timeline(
        ManagerFilter(
            employee=EmployeeFilter(uuids=[person]),
            engagement=EngagementFilter(uuids=[engagement]),
            from_date=None,
            to_date=None,
        )
    )

    objects = gql_timeline.objects
    if not objects:
        return ManagerTimeline()

    # Build a manager unit timeline for each manager object, keyed by manager UUID
    manager_unit_timelines: dict[UUID, Timeline[ManagerUnit]] = {}
    for manager_object in objects:
        unit_intervals = tuple(
            ManagerUnit(
                start=validity.validity.from_,
                end=mo_end_to_timeline_end(validity.validity.to),
                value=validity.org_unit_uuid,
            )
            for validity in manager_object.validities
            # Remove vacant managers
            if validity.employee_uuid == person
        )
        manager_unit_timelines[manager_object.uuid] = Timeline[ManagerUnit](
            intervals=combine_intervals(unit_intervals)
        )

    # Collect all interval endpoints across all the manager timelines
    endpoints = set(
        endpoint
        for manager_unit_timeline in manager_unit_timelines.values()
        for endpoint in manager_unit_timeline.get_interval_endpoints()
    )

    # For each interval, pick the manager unit (if any) from the manager timeline
    # with the "lowest" UUID that has a value in that interval
    sorted_manager_uuids = sorted(manager_unit_timelines)
    combined_unit_intervals: list[ManagerUnit] = []
    for start, end in pairwise(sorted(endpoints)):
        for manager_uuid in sorted_manager_uuids:
            try:
                manager_unit = manager_unit_timelines[manager_uuid].entity_at(start)
            except NoValueError:
                continue
            combined_unit_intervals.append(
                ManagerUnit(start=start, end=end, value=manager_unit.value)
            )
            break

    timeline = ManagerTimeline(
        manager_unit=Timeline[ManagerUnit](
            intervals=combine_intervals(tuple(combined_unit_intervals))
        ),
    )
    logger.info("MO manager timeline", timeline=timeline.dict())

    return timeline
