"""
Sync of the SD profession hierarchy to the job function classes in MO.
"""
from typing import Self
from uuid import UUID

import structlog
from anytree import NodeMixin
from sdclient.responses import ProfessionObj

from sdtoolplus.autogenerated_graphql_client import ClassFilter, FacetFilter
from sdtoolplus.depends import GraphQLClient

logger = structlog.stdlib.get_logger()


class JobFunctionNode(NodeMixin):
    """
    A representation of a job function node in the job function tree
    for either SD or MO.
    """
    def __init__(
        self,
        key: str,
        scope: str | None = None,
        name: str | None = None,
        parent: Self | None = None,
    ) -> None:
        """
        Construct a node in the job function tree.

        Args:
            key: the SD JobPositionIdentifier or the MO user_key
            scope: the SD job function scope or the MO class scope
            name: the name of the job function
            parent: the parent of this node
        """
        super().__init__()
        self.key = key
        self.scope = scope
        self.name = name
        self.parent = parent


def _get_sd_tree(sd_professions: list[ProfessionObj]) -> JobFunctionNode:
    """
    Build the tree of the professions SD.

    Args:
        sd_professions: The professions at the top of the SD hierarchy.

    Returns:
        The root of the tree.
    """

    def add(parent: JobFunctionNode, professions: list[ProfessionObj]) -> None:
        for profession in professions:
            node = JobFunctionNode(
                key=profession.JobPositionIdentifier,
                scope=profession.JobPositionLevelCode,
                # An employment always refers to a profession on level 0 in SD,
                # where a name is required. Level 1-3 are groupings of codes
                # used for statistics or budgeting, e.g. "all nurses", and can
                # be nameless.
                name=profession.JobPositionName
                if profession.JobPositionName is not None
                else "Ingen",
                parent=parent,
            )
            add(node, profession.Profession)

    root = JobFunctionNode(key="", scope="", name="root")
    add(root, sd_professions)
    return root


async def _get_mo_tree(
    graphql_client: GraphQLClient,
    engagement_job_function_facet: UUID,
) -> JobFunctionNode:
    """
    Build the tree of the job function classes in MO.

    Args:
        graphql_client: The GraphQL client.
        engagement_job_function_facet: The engagement_job_function facet UUID.

    Returns:
        The root of the tree.
    """
    mo_classes = await graphql_client.get_class(
        ClassFilter(facet=FacetFilter(uuids=[engagement_job_function_facet]))
    )

    classes = []
    for obj in mo_classes.objects:
        assert obj.current is not None
        classes.append(obj.current)

    # Create all the nodes, but do not build the tree structure yet
    nodes = {
        mo_class.uuid: JobFunctionNode(
            key=mo_class.user_key,
            scope=mo_class.scope,
            name=mo_class.name,
        )
        for mo_class in classes
    }

    # Build the tree structure by attaching parents to the nodes
    root = JobFunctionNode(key="", scope="", name="root")
    for mo_class in classes:
        node = nodes[mo_class.uuid]
        parent = mo_class.parent
        node.parent = nodes[parent.uuid] if parent is not None else root

    return root
