"""
Sync of the SD profession hierarchy to the job function classes in MO.
"""

import asyncio
from datetime import date
from typing import Self

import structlog
from anytree import NodeMixin
from sdclient.client import SDClient
from sdclient.requests import GetProfessionRequest
from sdclient.responses import ProfessionObj

from sdtoolplus.autogenerated_graphql_client import ClassFilter
from sdtoolplus.autogenerated_graphql_client import FacetFilter
from sdtoolplus.depends import GraphQLClient

logger = structlog.stdlib.get_logger()


class JobFunctionNode(NodeMixin):
    """
    A representation of a job function node in the job function tree
    for either SD or MO.
    """

    def __init__(
        self,
        key: str,
        scope: str | None = None,
        name: str | None = None,
        parent: Self | None = None,
    ) -> None:
        """
        Construct a node in the job function tree.

        Args:
            key: the SD JobPositionIdentifier or the MO user_key
            scope: the SD job function scope or the MO class scope
            name: the name of the job function
            parent: the parent of this node
        """
        super().__init__()
        self.key = key
        self.scope = scope
        self.name = name
        self.parent = parent


async def _get_sd_tree(
    sd_client: SDClient,
    institution_identifier: str,
) -> JobFunctionNode:
    """
    Build the tree of the professions SD.

    Args:
        sd_client: The SDClient

    Returns:
        The root of the tree.
    """
    logger.info("Build SD job position tree")

    sd_professions = await asyncio.to_thread(
        sd_client.get_profession,
        GetProfessionRequest(InstitutionIdentifier=institution_identifier),
    )

    def add(parent: JobFunctionNode, professions: list[ProfessionObj]) -> None:
        for profession in professions:
            node = JobFunctionNode(
                key=profession.JobPositionIdentifier,
                scope=profession.JobPositionLevelCode,
                # An employment always refers to a profession on level 0 in SD,
                # where a name is required. Level 1-3 are groupings of codes
                # used for statistics or budgeting, e.g. "all nurses", and can
                # be nameless.
                name=profession.JobPositionName
                if profession.JobPositionName is not None
                else "Ingen",
                parent=parent,
            )
            add(node, profession.Profession)

    root = JobFunctionNode(key="sd-root", name="SD Root")
    add(root, sd_professions.Profession)

    logger.info("Done building SD job position tree")

    return root


async def _get_mo_tree(
    graphql_client: GraphQLClient,
) -> JobFunctionNode:
    """
    Build the tree of the job function classes in MO.

    Args:
        graphql_client: The GraphQL client.

    Returns:
        The root of the tree.
    """
    logger.info("Build MO job function tree")

    mo_classes = await graphql_client.get_class(
        ClassFilter(facet=FacetFilter(user_keys=["engagement_job_function"]))
    )

    classes = []
    for obj in mo_classes.objects:
        assert obj.current is not None
        classes.append(obj.current)

    # Create all the nodes, but do not build the tree structure yet
    nodes = {
        mo_class.uuid: JobFunctionNode(
            key=mo_class.user_key,
            scope=mo_class.scope,
            name=mo_class.name,
        )
        for mo_class in classes
    }

    # Build the tree structure by attaching parents to the nodes
    root = JobFunctionNode(key="sd-root", name="SD Root")
    for mo_class in classes:
        node = nodes[mo_class.uuid]
        parent = mo_class.parent
        node.parent = nodes[parent.uuid] if parent is not None else root

    logger.info("Done building MO job function tree")

    return root


async def sync_professions(
    sd_client: SDClient,
    graphql_client: GraphQLClient,
    institution_identifier: str,
    force_class_start_date: date | None = None,
) -> None:
    """
    Sync the SD profession hierarchy to the job function hierarchy MO.

    This is done as follows:
    1) Build the tree of the SD professions.
    2) Build the tree of the MO job function classes.
    3) Iterate the SD tree and create/update all paths to the MO tree.
    4) Iterate the MO tree and terminate classes on paths not found in the SD tree.

    Args:
        sd_client: The SDClient
        graphql_client: The GraphQL client
        institution_identifier: The SD institution identifier
        force_class_start_date: Rewind the job function classes start date to this date.
            Old instances of MO may be missing job function classes in the early parts
            of an engagement timeline, since the job function sync per default is
            syncing job functions per todays date. This argument can be used to force
            job function classes to start from the given date. When set, all existing
            job function class validities will be rewinded too.
    """
    logger.info("Sync job functions")

    sd_tree = await _get_sd_tree(sd_client, institution_identifier)
    mo_tree = await _get_mo_tree(graphql_client)

    logger.info("Done syncing job functions")
